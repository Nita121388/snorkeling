#!/usr/bin/env node
// ledger.mjs — 台账事件流 CLI（唯一写 LEDGER 的入口之一；另一处是 hook-bridge.mjs）
// 用法见 RUNBOOK §8 / implement.md T4。
import { writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { LOOP_DIR } from './lib/paths.mjs';
import { appendEvent, readEvents, verifyLedger, nowIso, ledgerFiles } from './lib/ledger-io.mjs';
import { deriveRunStates, PARK_REASONS, RUN_STATES } from './lib/derive.mjs';

const argv = process.argv.slice(2);
const cmd = argv[0] ?? 'help';

function flag(name, def = null) {
    const i = argv.indexOf(`--${name}`);
    if (i < 0) return def;
    const v = argv[i + 1];
    return v && !v.startsWith('--') ? v : true;
}
function has(name) {
    return argv.includes(`--${name}`);
}
function die(msg) {
    console.error(`✗ ${msg}`);
    process.exit(1);
}

function cmdAdd() {
    const id = flag('id');
    const action = flag('action');
    const to = flag('to', null);
    if (!action) die('--action 必填');
    if (to && !RUN_STATES.includes(to)) die(`--to 必须是 ${RUN_STATES.join('|')}`);
    const verdict = flag('verdict', null);
    if (action === 'park' && verdict && !PARK_REASONS.includes(verdict)) {
        die(`park 的 --verdict 必须是 ${PARK_REASONS.join('|')}`);
    }
    const ev = appendEvent({
        ts: flag('ts', nowIso()),
        shift: flag('shift', 'night'),
        id,
        task: flag('task', null),
        action,
        from: flag('from', null),
        to,
        evidence: flag('evidence', null),
        commit: flag('commit', null),
        verdict,
    });
    if (has('json')) process.stdout.write(JSON.stringify(ev, null, 2) + '\n');
    else console.log(`${ev.ts} ${ev.action} ${ev.id ?? '-'} → ${ev.to ?? '-'}`);
}

function cmdTail() {
    const n = Number(flag('n', 30));
    const all = readEvents();
    const tail = all.slice(-n);
    if (has('json')) process.stdout.write(JSON.stringify(tail, null, 2) + '\n');
    else for (const e of tail) console.log(`${e.ts}  ${e.action.padEnd(7)} ${String(e.id ?? '-').padEnd(26)} ${e.from ?? '-'} → ${e.to ?? '-'}${e.verdict ? ` [${e.verdict}]` : ''}${e.commit ? ` @${e.commit}` : ''}`);
}

function cmdBlocked() {
    const states = deriveRunStates(readEvents());
    const parked = [...states.entries()].filter(([, s]) => s.runState === 'parked');
    if (has('json')) return process.stdout.write(JSON.stringify(parked.map(([id, s]) => ({ id, ...s })), null, 2) + '\n');
    if (!parked.length) return console.log('没有停泊项 ✓');
    for (const [id, s] of parked) console.log(`⏸ ${id.padEnd(28)} ${s.parkReason ?? '?'}  (${s.lastTs ?? '-'})`);
}

function cmdRender() {
    const events = readEvents();
    const states = deriveRunStates(events);
    const rows = [...states.entries()].map(([id, s]) => ({ id, ...s }));
    const open = rows.filter((r) => !['released', 'dropped'].includes(r.runState));
    const recent = rows
        .filter((r) => r.runState === 'released')
        .filter((r) => (r.lastTs ?? '') >= new Date(Date.now() - 14 * 864e5).toISOString())
        .sort((a, b) => String(b.lastTs).localeCompare(String(a.lastTs)));

    const table = (list, cols) => {
        if (!list.length) return '_（空）_\n';
        const head = `| ${cols.map((c) => c.t).join(' | ')} |\n|${cols.map(() => '---').join('|')}|\n`;
        return head + list.map((r) => `| ${cols.map((c) => (c.f(r) ?? '-')).join(' | ')} |`).join('\n') + '\n';
    };

    const md =
        `<!-- generated by loop/ledger.mjs render — do not edit 手改会被下次生成覆盖 -->\n\n` +
        `# LEDGER 视图\n\n> 生成于 ${nowIso()} · 源：${ledgerFiles().map((f) => f.split(/[\\/]/).pop()).join(', ') || '（无）'}\n\n` +
        `## 进行中\n\n` +
        table(open, [
            { t: '包', f: (r) => r.id },
            { t: '状态', f: (r) => r.runState },
            { t: '原因', f: (r) => r.parkReason },
            { t: 'commit', f: (r) => r.commit },
            { t: '最近', f: (r) => r.lastTs },
        ]) +
        `\n## 近 14 天已发布\n\n` +
        table(recent, [
            { t: '包', f: (r) => r.id },
            { t: 'commit', f: (r) => r.commit },
            { t: '时间', f: (r) => r.lastTs },
        ]);

    const out = join(LOOP_DIR, 'LEDGER.md');
    writeFileSync(out, md, 'utf8');
    console.log(`wrote loop/LEDGER.md (${open.length} open, ${recent.length} released)`);
}

function cmdSelfTest() {
    const expectBroken = argv.includes('--expect=broken') || (argv.includes('--expect') && argv[argv.indexOf('--expect') + 1] === 'broken');
    if (expectBroken) process.env.LOOP_SLOPPY = '1';

    // 用临时目录，绝不污染真实台账
    const sandbox = mkdtempSync(join(tmpdir(), 'loop-ledger-'));

    const { deriveRunStates: fold } = { deriveRunStates };
    const cases = [];
    const check = (name, fn) => {
        try {
            fn();
            cases.push({ name, ok: true });
        } catch (e) {
            cases.push({ name, ok: false, err: e.message });
        }
    };
    const eq = (a, b, m) => {
        if (JSON.stringify(a) !== JSON.stringify(b)) throw new Error(`${m ?? ''} expected ${JSON.stringify(b)} got ${JSON.stringify(a)}`);
    };

    check('appendEvent 字段齐全', () => {
        const ev = appendEvent({ id: '__selftest__', action: 'note', to: null, shift: 'hook' }, sandbox);
        if (!ev.ts || ev.id !== '__selftest__') throw new Error('bad event');
    });
    check('readEvents 能读回刚写的行', () => {
        const all = readEvents({ dir: sandbox });
        if (!all.some((e) => e.id === '__selftest__')) throw new Error('not found');
    });
    check('verifyLedger 无问题', () => {
        const p = verifyLedger(sandbox);
        if (p.length) throw new Error(p.join('; '));
    });
    check('折叠 queued→running→green', () => {
        const m = fold([
            { id: 'a', action: 'approve', from: null, to: 'queued', ts: '2026-11-05T01:00:00Z' },
            { id: 'a', action: 'pick', from: 'queued', to: 'running', ts: '2026-11-05T02:00:00Z' },
            { id: 'a', action: 'verify', from: 'running', to: 'green', ts: '2026-11-05T03:00:00Z' },
        ]);
        eq(m.get('a').runState, 'green');
    });
    check('park 原因落位', () => {
        const m = fold([{ id: 'b', action: 'park', from: 'running', to: 'parked', verdict: 'human-wall' }]);
        eq(m.get('b').parkReason, 'human-wall');
    });
    check('过期语义：accepted 不可再跑', () => {
        const m = fold([{ id: 'c', action: 'accept', from: 'committed', to: 'accepted' }]);
        if (m.get('c').runState !== 'accepted') throw new Error('bad');
    });
    check('无效 to 值被拒绝（写库前校验）', () => {
        if (RUN_STATES.includes('bogus')) throw new Error('bogus 不该在枚举里');
    });
    check('PARK_REASONS 覆盖 5 种', () => {
        eq(PARK_REASONS.length, 5);
    });

    const passed = cases.filter((c) => c.ok).length;
    const failed = cases.length - passed;
    for (const c of cases.filter((x) => !x.ok)) console.error(`  ✗ ${c.name}: ${c.err}`);
    console.log(`ledger self-test: ${passed} passed, ${failed} failed${expectBroken ? ' (expected-red)' : ''}`);
    process.exit(expectBroken ? (failed > 0 ? 0 : 1) : failed === 0 ? 0 : 1);
}

const help = `ledger.mjs — loop 台账事件流

  add --id <id> --action <a> [--to <state>] [--from <s>] [--shift night]
      [--evidence <ptr>] [--commit <sha>] [--verdict <parkReason>] [--json]
  tail [-n 30] [--json]
  blocked [--json]
  render
  self-test [--expect=broken]
`;

switch (cmd) {
    case 'add':
        cmdAdd();
        break;
    case 'tail':
        cmdTail();
        break;
    case 'blocked':
        cmdBlocked();
        break;
    case 'render':
        cmdRender();
        break;
    case 'self-test':
        cmdSelfTest();
        break;
    default:
        process.stdout.write(help);
}
