// ============ 渲染 ============
const $ = (id) => document.getElementById(id);
let currentScenario = SCENARIOS[0];
let lastStamp = "";

function render(scenario) {
    currentScenario = scenario;
    const card = $("agent-card");
    card.dataset.state = scenario.state;
    card.classList.toggle("disabled-card", !!scenario.disabled);

    $("hdr-logo").innerHTML = LOGOS[scenario.provider] ?? "";
    $("photo-inner").innerHTML = scenario.state === "unbound"
        ? '<span class="q-mark">?</span>'
        : LOGOS[scenario.provider] ?? "";

    $("hdr-title").textContent = `${scenario.provider} \u00b7 ${scenario.title}`;
    $("chip-title").textContent = scenario.title;
    const dotColor = getComputedStyle(card).getPropertyValue("--state-color").trim();
    $("chip-dot").style.background = dotColor;
    $("chip-dot").className = `chip-dot ${scenario.pulse ? "is-pulsing" : ""}`;

    $("f-title").textContent = scenario.title;
    $("f-status").textContent = scenario.status;
    const sdot = $("status-dot");
    sdot.className = `status-dot ${scenario.pulse || ""}`.trim();

    $("f-output").textContent = scenario.output;

    const noteEl = $("f-note");
    if (scenario.hintNote) {
        noteEl.textContent = "Click to register a note\u2026";
        noteEl.className = "dd-note is-hint";
    } else if (!scenario.note && !scenario.tags.length) {
        noteEl.textContent = "\u2014";
        noteEl.className = "dd-note";
    } else {
        noteEl.innerHTML =
            escapeHtml(scenario.note) +
            scenario.tags.map((t) => ` <span class="tag">${escapeHtml(t)}</span>`).join("");
        noteEl.className = "dd-note";
    }

    const sessLink = $("f-sessions");
    sessLink.textContent = scenario.sessions;
    sessLink.appendChild(Object.assign(document.createElementNS("http://www.w3.org/2000/svg", "svg"), { className: "chev", viewBox: "0 0 24 24", innerHTML: '<path d="M9 6l6 6-6 6"/>' }));

    $("f-sid").textContent = scenario.sid;

    // 印章：状态跳变时盖章动画
    const stamp = $("stamp");
    stamp.textContent = scenario.stamp;
    stamp.style.setProperty("--stamp-color", "");
    if (lastStamp !== scenario.stamp) {
        stamp.classList.remove("just-stamped");
        void stamp.offsetWidth; // restart animation
        stamp.classList.add("just-stamped");
    }
    lastStamp = scenario.stamp;

    document.querySelectorAll(".scenario-btn").forEach((btn) => {
        btn.classList.toggle("is-active", btn.dataset.scenario === scenario.id);
    });
}

function escapeHtml(s) {
    return String(s).replace(/[&<>"']/g, (c) =>
        ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

// ============ 场景栏 ============
function buildScenarioBar() {
    const bar = $("scenario-bar");
    SCENARIOS.forEach((sc, idx) => {
        if (idx === 7 || idx === SCENARIOS.length - 2) {
            const sep = document.createElement("span");
            sep.className = "scenario-sep";
            bar.appendChild(sep);
        }
        const btn = document.createElement("button");
        btn.className = "scenario-btn";
        btn.dataset.scenario = sc.id;
        btn.textContent = sc.label;
        btn.addEventListener("click", () => render(sc));
        bar.appendChild(btn);
    });
    const sep = document.createElement("span");
    sep.className = "scenario-sep";
    bar.appendChild(sep);

    // 印章开关（评审用）
    const stampToggle = document.createElement("label");
    stampToggle.className = "scenario-toggle";
    stampToggle.innerHTML = '<input type="checkbox" checked> stamp';
    stampToggle.querySelector("input").addEventListener("change", (e) => {
        $("agent-card").classList.toggle("no-stamp", !e.target.checked);
    });
    bar.appendChild(stampToggle);

    // 桌面明暗（对照卡片恒浅色）
    const deskToggle = document.createElement("label");
    deskToggle.className = "scenario-toggle";
    deskToggle.innerHTML = '<input type="checkbox"> dark desk';
    deskToggle.querySelector("input").addEventListener("change", (e) => {
        $("desk").classList.toggle("is-dark", e.target.checked);
    });
    bar.appendChild(deskToggle);
}

// ============ 交互演示 ============
function toast(msg) {
    const el = $("toast");
    el.textContent = msg;
    el.classList.add("show");
    clearTimeout(el._t);
    el._t = setTimeout(() => el.classList.remove("show"), 2200);
}

function wireInteractions() {
    $("copy-btn").addEventListener("click", () => {
        navigator.clipboard?.writeText(currentScenario.sid).then(
            () => toast("Session id copied"),
            () => toast("Clipboard unavailable (prototype)")
        );
    });

    $("f-note").addEventListener("click", () =>
        toast("[P1] opens existing AI-session note editor"));
    $("f-sessions").addEventListener("click", (e) => {
        e.preventDefault();
        toast("[P1] jumps to Sessions view \u00b7 filter projectPath + source");
    });

    // 折叠/展开生命周期
    const body = document.querySelector(".mock-block-body");
    const chip = $("agent-chip");
    function setCardVisible(visible) {
        body.classList.toggle("card-hidden", !visible);
        chip.setAttribute("aria-expanded", String(visible));
        $("toggle-card-btn").setAttribute("aria-pressed", String(visible));
        $("log").textContent = visible
            ? "Card expanded \u2014 shown at launch, before terminal output takes over."
            : "Card collapsed to header chip \u2014 happens automatically on first output.";
    }
    $("toggle-card-btn").addEventListener("click", () =>
        setCardVisible(body.classList.contains("card-hidden")));
    chip.addEventListener("click", () => setCardVisible(true));

    if (currentScenario.disabled) {
        card.querySelectorAll("button, a, [role=button]").forEach((el) => (el.tabIndex = -1));
    }
}

buildScenarioBar();
wireInteractions();
render(SCENARIOS[0]);
