package persona

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

// rosterLineCap is the L0 hard cap before folding (design §7 rule: roster
// stays ≤50 lines; the fold dimension itself is A4's open question).
const rosterLineCap = 50

// RosterPath is <root>/.index/PERSONAS.md (derived, gitignored, rebuilt).
func RosterPath(root string) (string, error) {
	rootResolved, err := ResolveRoot(root)
	if err != nil {
		return "", err
	}
	return filepath.Join(rootResolved, ".index", "PERSONAS.md"), nil
}

// WriteRoster regenerates the roster from a directory scan. Atomic: written
// to a temp file next to the target, then renamed into place.
func WriteRoster(root string) (string, error) {
	rootResolved, err := ResolveRoot(root)
	if err != nil {
		return "", err
	}
	personas, err := List(rootResolved)
	if err != nil {
		return "", err
	}
	path := filepath.Join(rootResolved, ".index", "PERSONAS.md")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", fmt.Errorf("creating .index dir: %w", err)
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(renderRoster(personas, time.Now())), 0o644); err != nil {
		return "", fmt.Errorf("writing roster: %w", err)
	}
	if err := os.Rename(tmp, path); err != nil {
		os.Remove(tmp)
		return "", fmt.Errorf("replacing roster: %w", err)
	}
	return path, nil
}

// renderRoster emits the L0 index: one line per persona
// (emoji + id | role | provider/model | relative home), no display name —
// the roster is the injection surface, and every token must earn its place.
func renderRoster(personas []Persona, now time.Time) string {
	var b strings.Builder
	b.WriteString("<!-- GENERATED by wsh persona; do not edit. Rescan: wsh persona list -->\n")
	b.WriteString("# PERSONAS\n\n")
	if len(personas) == 0 {
		b.WriteString("（空：还没有人设）\n")
		return b.String()
	}
	sorted := append([]Persona(nil), personas...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].ID < sorted[j].ID })
	for _, p := range sorted {
		b.WriteString(fmt.Sprintf("%s | %s | %s | ./%s\n", rosterIDCell(p), orDash(p.Role), rosterStack(p), p.ID))
	}
	if len(personas) > rosterLineCap {
		b.WriteString(fmt.Sprintf("\n<!-- %d 个人设超出 %d 行硬顶：折叠分组维度见 A4 -->\n", len(personas), rosterLineCap))
	}
	b.WriteString(fmt.Sprintf("\n<!-- scanned %s -->\n", now.UTC().Format(time.RFC3339)))
	return b.String()
}

func rosterIDCell(p Persona) string {
	if p.Emoji != "" {
		return p.Emoji + " " + p.ID
	}
	return p.ID
}

func rosterStack(p Persona) string {
	if p.Provider == "" && p.Model == "" {
		return "—"
	}
	if p.Provider == "" {
		return p.Model
	}
	if p.Model == "" {
		return p.Provider
	}
	return p.Provider + "/" + p.Model
}

func orDash(s string) string {
	if strings.TrimSpace(s) == "" {
		return "—"
	}
	return strings.TrimSpace(s)
}
