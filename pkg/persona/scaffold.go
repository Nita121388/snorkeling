// providerContractTemplate is the single generated contract consumed by
// pi/codex (AGENTS.md), Claude Code (CLAUDE.md) and gemini (GEMINI.md).
// The content is identical: one template, three file names, zero drift.
func providerContractTemplate(p Persona) string {
	var b strings.Builder
	b.WriteString("<!-- " + GeneratedHeader + " -->\n\n")
	b.WriteString("# " + displayName(p) + "\n\n")
	if p.Role != "" {
		b.WriteString(p.Role + "\n\n")
	}
	b.WriteString("## 记忆（先读这个）\n\n")
	b.WriteString("- `.persona/MEMORY/facts.md` — 长期事实（头部的 ## TL;DR 是常驻注入面）\n")
	b.WriteString("- `.persona/MEMORY/lessons.md` — 经验教训（按标题分节）\n")
	b.WriteString("- `.persona/MEMORY/playbook/` — 操作手册：一类事一个文件\n")
	b.WriteString("- `.persona/MEMORY/journal.md` — 当班流水（按月轮转）\n\n")
	b.WriteString("## 写入纪律\n\n")
	b.WriteString("- journal.md 可直接 append；facts / lessons / CHARTER 只能写 `MEMORY/inbox.md` 提议，人批准后入档\n")
	b.WriteString("- 工作产物一律进 `work/`，不要散落在据点根目录\n\n")
	b.WriteString("## 同事规则\n\n")
	b.WriteString("- 名册在 `../.index/PERSONAS.md`（或同级目录）；了解同事 = 显式读其 CHARTER，正文不自动注入\n")
	b.WriteString("- 改同事的记忆必须写对方的 `MEMORY/inbox.md` 提议，注明出处\n")
	return b.String()
}

// rootPointerTemplate is the ≤20-line root AGENTS.md: a pointer, not a copy.
