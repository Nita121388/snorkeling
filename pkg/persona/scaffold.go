func displayName(p Persona) string {
	if p.Emoji != "" {
		return p.Emoji + " " + p.Name
	}
	return p.Name
}

func readPersonaFile(path string) (*Persona, error) {
	barr, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var p Persona
	if err := json.Unmarshal(barr, &p); err != nil {
		return nil, fmt.Errorf("parsing %s: %w", path, err)
	}
	return &p, nil
}

// Get returns the persona and its CHARTER.md body.
func Get(root, id string) (*Persona, string, error) {
	rootResolved, err := ResolveRoot(root)
	if err != nil {
		return nil, "", err
	}
	if err := ValidateID(id); err != nil {
		return nil, "", err
	}
	p, err := readPersonaFile(filepath.Join(personaDir(rootResolved, id), ".persona", "persona.json"))
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil, "", fmt.Errorf("%w: %s", ErrNotFound, id)
		}
		return nil, "", err
	}
	charter, _ := os.ReadFile(filepath.Join(personaDir(rootResolved, id), ".persona", "CHARTER.md"))
	return p, string(charter), nil
}

// List scans <root>/<id>/.persona/persona.json and returns personas sorted by id.
func List(root string) ([]Persona, error) {
	rootResolved, err := ResolveRoot(root)
	if err != nil {
		return nil, err
	}
	entries, err := os.ReadDir(rootResolved)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil, nil
		}
		return nil, err
	}
	var out []Persona
	for _, ent := range entries {
		if !ent.IsDir() || strings.HasPrefix(ent.Name(), ".") {
			continue
		}
		p, err := readPersonaFile(filepath.Join(rootResolved, ent.Name(), ".persona", "persona.json"))
		if err != nil {
			continue // not a persona home base; the roster only lists real personas
		}
		out = append(out, *p)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out, nil
}

func currentUser() string {
	u := os.Getenv("USER")
	if u == "" {
		u = os.Getenv("USERNAME")
	}
	if u == "" {
		return "unknown"
	}
	return u
}
