// GeneratedHeader marks every scaffolded file that is a generated artifact.
// CHARTER.md and MEMORY/*.md templates carry it too: the skeleton is
// generated, the human owns what grows inside.
const GeneratedHeader = "GENERATED by wsh persona; edit .persona/CHARTER.md or MEMORY/ instead."

const generatedJSONKey = "_generated"
const scaffoldStamp = "wsh persona scaffold v1"

// Options configures Create.
type Options struct {
	Root     string // empty -> ResolveRoot("")
	Name     string // display name; the id (directory) is Slugify(Name)
	Emoji    string
	Role     string // one-line duty, rendered into the roster L0 line
	Provider string
	Model    string
	DryRun   bool // default: plan only, zero disk writes
	Now      func() time.Time
	// Creator overrides the provenance "createdBy" entry (A2.5 sets agent identity).
	Creator *Provenance
	// OriginInfo overrides the machine origin entry.
	OriginInfo *Origin
	// Agent marks the caller as an agent (A2.5 gate, design §2). Non-nil and
	// DryRun means "propose, do not scaffold"; non-nil and applied means the
	// scaffold is stamped createdBy.kind=agent.
	Agent *Provenance
	// ApprovedBy is stamped when a human approves an agent proposal.
	ApprovedBy *Provenance
	// Charter is an optional CHARTER.md draft (--charter-file). It replaces
	// the generated skeleton at apply time; it is never written on propose.
	Charter string
	// MemoryDraft is an optional session-note draft (--memory-from-session).
	// It is appended to MEMORY/inbox.md as a facts proposal, never to
	// facts.md directly (memory discipline §6).
	MemoryDraft string
}

// PlannedFile is one file the scaffold would write, with a small preview.
type PlannedFile struct {
	Path string `json:"path"`
	// Bytes is the full file body (Create writes exactly this, guarded by
	// TestCreateWritesFullFiles). It is deliberately not JSON-marshalled:
	// the wire shows Preview only, so `--json` stays small and preview-y.
	Bytes string `json:"-"`
	// Preview is a one-line excerpt for dry-run reports and `--json`.
	Preview string `json:"preview,omitempty"`
	Exists  bool   `json:"exists"` // already on disk (idempotent hit)
}

// CreateResult reports what Create did (or would do under --dry-run).
type CreateResult struct {
	Persona Persona       `json:"persona"`
	Dir     string        `json:"dir"`
	Files   []PlannedFile `json:"files,omitempty"`
	Created bool          `json:"created"` // false = idempotent hit, nothing written
	Applied bool          `json:"applied"` // true = written to disk
	// Proposal is set when an agent caller was gated into the propose path
	// (design §2): a proposal file was written (or reused) and NO home base
	// was scaffolded.
	Proposal *Proposal `json:"proposal,omitempty"`
	// ProposalReused reports that an identical pending proposal already existed.
	ProposalReused bool `json:"proposalReused,omitempty"`
}

// Create scaffolds a persona home base. Idempotent: if <root>/<id>/.persona/
// persona.json already exists it is read back and returned untouched with
// Created=false and zero writes (design: an existing slug is reused, never
// overwritten). DryRun performs no MkdirAll and no writes at all.
func Create(opts Options) (*CreateResult, error) {
	if strings.TrimSpace(opts.Name) == "" {
		return nil, errors.New("persona name must not be empty")
	}
	root, err := ResolveRoot(opts.Root)
	if err != nil {
		return nil, err
	}
	id := Slugify(opts.Name)
	dir := personaDir(root, id)
	identityPath := filepath.Join(dir, ".persona", "persona.json")

	// Idempotency check first: an existing persona is returned untouched.
	if existing, err := readPersonaFile(identityPath); err == nil {
		return &CreateResult{
			Persona: *existing,
			Dir:     dir,
			Created: false,
			Applied: false,
		}, nil
	} else if !errors.Is(err, fs.ErrNotExist) {
		return nil, fmt.Errorf("checking existing persona %q: %w", id, err)
	}

	now := time.Now()
	if opts.Now != nil {
		now = opts.Now()
	}

	// A2.5 propose gate (design §2, decision D1): an agent identity without
	// --yes proposes instead of scaffolding. The human path below is unchanged
	// (F-1112 frozen criteria).
	if opts.Agent != nil && opts.DryRun {
		prop, reused, err := Propose(opts)
		if err != nil {
			return nil, err
		}
		if prop != nil {
			return &CreateResult{Dir: dir, Created: true, Applied: false, Proposal: prop, ProposalReused: reused}, nil
		}
		// prop == nil: the persona appeared between the idempotency check
		// above and here; fall through and let the scaffold path read it back.
	}

	p := Persona{
		SchemaVersion: SchemaVersion,
		ID:            id,
		Name:          strings.TrimSpace(opts.Name),
		Emoji:         strings.TrimSpace(opts.Emoji),
		Role:          strings.TrimSpace(opts.Role),
		Provider:      strings.TrimSpace(opts.Provider),
		Model:         strings.TrimSpace(opts.Model),
		CreatedAt:     now.UTC().Format(time.RFC3339),
		CreatedBy:     opts.Creator,
		ApprovedBy:    opts.ApprovedBy,
		Origin:        opts.OriginInfo,
	}
	if p.CreatedBy == nil && opts.Agent != nil {
		agent := *opts.Agent
		if agent.Kind == "" {
			agent.Kind = "agent"
		}
		if agent.Ts == "" {
			agent.Ts = p.CreatedAt
		}
		p.CreatedBy = &agent
	}
	if p.CreatedBy == nil {
		p.CreatedBy = &Provenance{Kind: "human", Name: currentUser(), Ts: p.CreatedAt}
	}
	if p.Origin == nil {
		p.Origin = &Origin{Platform: hostPlatform()}
	}

	files := plannedFiles(dir, p)
	if opts.DryRun {
		return &CreateResult{Persona: p, Dir: dir, Files: files, Created: true, Applied: false}, nil
	}

	for _, f := range files {
		if dir := filepath.Dir(f.Path); dir != "." {
			if err := os.MkdirAll(dir, 0o755); err != nil {
				return nil, fmt.Errorf("creating directory %s: %w", dir, err)
			}
		}
		if err := os.WriteFile(f.Path, []byte(f.Bytes), 0o644); err != nil {
			return nil, fmt.Errorf("writing %s: %w", f.Path, err)
		}
	}
	// Optional drafts (--charter-file / --memory-from-session). Both stay
	// inside the memory discipline: the session note goes to inbox.md, never
	// to facts.md directly.
	if opts.Charter != "" {
		charterPath := filepath.Join(dir, ".persona", "CHARTER.md")
		if err := os.WriteFile(charterPath, []byte(opts.Charter), 0o644); err != nil {
			return nil, fmt.Errorf("writing %s: %w", charterPath, err)
		}
	}
	if opts.MemoryDraft != "" {
		if err := appendInbox(root, id, "facts", opts.MemoryDraft, opts.Agent, now); err != nil {
			return nil, err
		}
	}
	if _, err := WriteRoster(root); err != nil {
		return nil, err
	}
	return &CreateResult{Persona: p, Dir: dir, Files: files, Created: true, Applied: true}, nil
}

// plannedFiles builds the full scaffold list (design §3.1). Order is stable.
func plannedFiles(dir string, p Persona) []PlannedFile {
	type entry struct {
		rel  string
		body func() string
	}
	entries := []entry{
		{".persona/persona.json", func() string { return marshalIndent(p) + "\n" }},
		{".persona/persona.local.json", func() string {
			return marshalIndent(PersonaLocal{SchemaVersion: SchemaVersion, Generated: scaffoldStamp}) + "\n"
		}},
		{".persona/CHARTER.md", func() string { return charterTemplate(p) }},
		{".persona/MEMORY/facts.md", func() string { return factsTemplate(p) }},
		{".persona/MEMORY/lessons.md", func() string { return lessonsTemplate(p) }},
		{".persona/MEMORY/journal.md", func() string { return journalTemplate(p) }},
		{".persona/MEMORY/inbox.md", func() string { return inboxTemplate(p) }},
		{".persona/MEMORY/playbook/.gitkeep", func() string { return "" }},
		{".persona/MEMORY/archive/.gitkeep", func() string { return "" }},
		{".persona/agents/AGENTS.md", func() string { return providerContractTemplate(p) }},
		{".persona/agents/CLAUDE.md", func() string { return providerContractTemplate(p) }},
		{".persona/agents/GEMINI.md", func() string { return providerContractTemplate(p) }},
		{"AGENTS.md", func() string { return rootPointerTemplate(p) }},
		{"work/.gitkeep", func() string { return "" }},
		{".gitignore", func() string { return gitignoreTemplate() }},
	}
	out := make([]PlannedFile, 0, len(entries))
	for _, e := range entries {
		full := filepath.Join(dir, filepath.FromSlash(e.rel))
		// Bytes is the full file body, not a preview: Create writes exactly
		// what it reports. (An earlier version truncated this field at 400
		// bytes for display, which corrupted every scaffolded file longer
		// than that — including persona.json once provenance pushed it over.)
		// Preview stays wire-only: first line, capped at 120 chars.
		preview := e.body()
		if idx := strings.IndexByte(preview, '\n'); idx >= 0 {
			preview = preview[:idx]
		}
		if len(preview) > 120 {
			preview = preview[:120] + "…"
		}
		out = append(out, PlannedFile{Path: full, Bytes: e.body(), Preview: preview})
	}
	return out
}

func marshalIndent(v any) string {
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		// All scaffolded types are plain structs; marshal failures are bugs.
		return "{}"
	}
	return string(b)
}

func charterTemplate(p Persona) string {
	var b strings.Builder
	b.WriteString("<!-- " + GeneratedHeader + " -->\n\n")
	b.WriteString("# " + displayName(p) + " — 职责书（CHARTER）\n\n")
	b.WriteString("> 人写为主，AI 提议修订：改动走 MEMORY/inbox.md。\n\n")
	b.WriteString("## 职责\n\n- （用一句话到几句话写清：管什么、不管什么）\n\n")
	b.WriteString("## 边界\n\n- （明确不做什么，防止越界）\n")
	return b.String()
}

