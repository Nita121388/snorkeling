func writeMemoryFixture(t *testing.T, root, id string, factsEntries, lessonEntries []string) (string, string) {
	t.Helper()
	var facts strings.Builder
	facts.WriteString("<!-- GENERATED by wsh hero; edit .hero/CHARTER.md or MEMORY/ instead. -->\n\n")
	facts.WriteString("# 长期事实（facts）\n\n## TL;DR\n\n<!-- 机器维护的精选（≤5 条）；注入面只带本节 -->\n\n- 旧摘要 A\n- 旧摘要 B\n\n## 正文\n\n<!-- 按需读；新事实走 inbox.md 提议入档 -->\n")
	for _, entry := range factsEntries {
		facts.WriteString("- " + entry + "\n")
	}
	var lessons strings.Builder
	lessons.WriteString("<!-- GENERATED by wsh hero; edit .hero/CHARTER.md or MEMORY/ instead. -->\n\n")
	lessons.WriteString("# 经验教训（lessons）\n\n")
	for _, entry := range lessonEntries {
		lessons.WriteString("- " + entry + "\n")
	}
	factsPath := heroMemoryPath(root, id, "facts.md")
	lessonsPath := heroMemoryPath(root, id, "lessons.md")
	if err := os.WriteFile(factsPath, []byte(facts.String()), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(lessonsPath, []byte(lessons.String()), 0o644); err != nil {
		t.Fatal(err)
	}
	return facts.String(), lessons.String()
}

func TestDistillDeduplicatesKeepsCoverageAndUndo(t *testing.T) {
	root := makeHeroRoot(t, "alpha")
	factsEntries := make([]string, 0, 24)
	for i := 0; i < 20; i++ {
		factsEntries = append(factsEntries, fmt.Sprintf("事实-%02d", i))
	}
	factsEntries = append(factsEntries, "事实-00", "事实-07", " 事实-12  ", "新事实-21")
	lessons := []string{"教训-A", "教训-B", "教训-A", "教训-C"}
	factsBefore, lessonsBefore := writeMemoryFixture(t, root, "alpha", factsEntries, lessons)

	dry, err := Distill(root, "alpha", DistillOptions{Threshold: 5, DryRun: true, Now: func() time.Time { return testNow }})
	if err != nil {
		t.Fatalf("dry-run Distill: %v", err)
	}
	if dry.Changed == false || dry.DryRun == false || dry.Backup != "" {
		t.Fatalf("dry result = %+v, want changed/no backup", dry)
	}
	if readFileString(t, dry.Facts) != factsBefore || readFileString(t, dry.Lessons) != lessonsBefore {
		t.Fatal("dry-run wrote files")
	}

	result, err := Distill(root, "alpha", DistillOptions{Threshold: 5, Now: func() time.Time { return testNow }})
	if err != nil {
		t.Fatalf("Distill: %v", err)
	}
	if result.Before != len(factsEntries)+len(lessons) {
		t.Fatalf("before = %d, want %d", result.Before, len(factsEntries)+len(lessons))
	}
	if result.Removed != 4 || result.After != result.Before-result.Removed {
		t.Fatalf("removed = %d, after = %d (want 4 / %d)", result.Removed, result.After, result.Before-4)
	}
	if result.Backup == "" {
		t.Fatal("no backup written")
	}
	if result.TLDR > TLDREntryCap {
		t.Fatalf("TL;DR has %d entries, cap is %d", result.TLDR, TLDREntryCap)
	}
	factsAfter := readFileString(t, result.Facts)
	lessonsAfter := readFileString(t, result.Lessons)
	// Coverage: every unique entry from both files must survive.
	for i := 0; i < 20; i++ {
		entry := fmt.Sprintf("事实-%02d", i)
		if !strings.Contains(factsAfter, entry) {
			t.Fatalf("lost fact %s", entry)
		}
	}
	for _, entry := range []string{"新事实-21", "教训-A", "教训-B", "教训-C"} {
		body := factsAfter
		if strings.HasPrefix(entry, "教训") {
			body = lessonsAfter
		}
		if !strings.Contains(body, entry) {
			t.Fatalf("lost entry %s", entry)
		}
	}
	if strings.Contains(factsAfter, "旧摘要 A") {
		t.Fatal("stale hand-written TL;DR entry should be replaced by distilled entries")
	}
	if !strings.Contains(factsAfter, "## TL;DR") || !strings.Contains(factsAfter, "## 正文") {
		t.Fatalf("section structure lost:\n%s", factsAfter)
	}
	if strings.Count(lessonsAfter, "教训-A") != 1 {
		t.Fatalf("lesson duplicate survived:\n%s", lessonsAfter)
	}
	// Exact-byte rollback.
	undo, err := UndoDistill(root, "alpha")
	if err != nil {
		t.Fatalf("UndoDistill: %v", err)
	}
	if undo != result.Backup {
		t.Fatalf("undo picked %q, want %q", undo, result.Backup)
	}
	if readFileString(t, result.Facts) != factsBefore || readFileString(t, result.Lessons) != lessonsBefore {
		t.Fatal("undo did not restore exact bytes")
	}
}

func TestDistillBelowThresholdCleanIsNoop(t *testing.T) {
	root := makeHeroRoot(t, "alpha")
	factsBefore, lessonsBefore := writeMemoryFixture(t, root, "alpha",
		[]string{"唯一事实"}, []string{"唯一教训"})
	result, err := Distill(root, "alpha", DistillOptions{Threshold: 100, Now: func() time.Time { return testNow }})
	if err != nil {
		t.Fatalf("Distill: %v", err)
	}
	if result.Changed || result.Backup != "" || result.Before != 2 || result.After != 2 {
		t.Fatalf("clean vault was rewritten: %+v", result)
	}
	if readFileString(t, result.Facts) != factsBefore || readFileString(t, result.Lessons) != lessonsBefore {
		t.Fatal("no-op distill changed bytes")
	}
	if _, err := UndoDistill(root, "alpha"); err == nil {
		t.Fatal("undo should fail when no backup exists")
	}
}

func TestDistillCuratedTLDRSurvivesEmptyBody(t *testing.T) {
	root := makeHeroRoot(t, "alpha")
	factsBefore, _ := writeMemoryFixture(t, root, "alpha", nil, nil)
	result, err := Distill(root, "alpha", DistillOptions{Threshold: 1, Now: func() time.Time { return testNow }})
	if err != nil {
		t.Fatalf("Distill: %v", err)
	}
	factsAfter := readFileString(t, result.Facts)
	if !strings.Contains(factsAfter, "旧摘要 A") || !strings.Contains(factsAfter, "旧摘要 B") {
		t.Fatalf("curated TL;DR lost when body has no entries:\n%s", factsAfter)
	}
	_ = factsBefore
}

func TestDistillNormalizesWhitespaceDuplicates(t *testing.T) {
	out, before, after := dedupeBullets([]string{
		"# head",
		"- Alpha  Fact",
		"- alpha fact",
		"",
		"- Beta",
		"<!-- comment -->",
	})
	if before != 3 || after != 2 {
		t.Fatalf("before/after = %d/%d, want 3/2", before, after)
	}
	if !strings.Contains(out, "# head") || !strings.Contains(out, "<!-- comment -->") {
		t.Fatalf("non-bullet lines lost:\n%s", out)
	}
}
