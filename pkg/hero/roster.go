package hero

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

// rosterLineCap is the L0 hard cap before folding (design §7 rule: roster
// stays ≤50 lines; the fold dimension itself is A4's open question).
const rosterLineCap = 50

// dormantAfter is design §5/§7: a hero that has not appeared for 90 days
// is marked dormant in the roster. Dormant is a display state, never a delete.
const dormantAfter = 90 * 24 * time.Hour

// RosterPath is <root>/.index/HEROES.md (derived, gitignored, rebuilt).
func RosterPath(root string) (string, error) {
	rootResolved, err := ResolveRoot(root)
	if err != nil {
		return "", err
	}
	return filepath.Join(rootResolved, ".index", "HEROES.md"), nil
}

// WriteRoster regenerates the roster from a directory scan. Atomic: written
// to a temp file next to the target, then renamed into place.
func WriteRoster(root string) (string, error) {
	rootResolved, err := ResolveRoot(root)
	if err != nil {
		return "", err
	}
	heroes, err := List(rootResolved)
	if err != nil {
		return "", err
	}
	path := filepath.Join(rootResolved, ".index", "HEROES.md")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", fmt.Errorf("creating .index dir: %w", err)
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(renderRoster(rootResolved, heroes, time.Now())), 0o644); err != nil {
		return "", fmt.Errorf("writing roster: %w", err)
	}
	if err := os.Rename(tmp, path); err != nil {
		os.Remove(tmp)
		return "", fmt.Errorf("replacing roster: %w", err)
	}
	return path, nil
}

// renderRoster emits the L0 index: one line per hero
// (emoji + id | role | provider/model | relative home), no display name —
// the roster is the injection surface, and every token must earn its place.
// A hero whose last-active proxy is older than 90 days gets a 💤 prefix.
func renderRoster(root string, heroes []Hero, now time.Time) string {
	var b strings.Builder
	b.WriteString("<!-- GENERATED by wsh hero; do not edit. Rescan: wsh hero list -->\n")
	b.WriteString("# PERSONAS\n\n")
	if len(heroes) == 0 {
		b.WriteString("（空：还没有人设）\n")
		return b.String()
	}
	sorted := append([]Hero(nil), heroes...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].ID < sorted[j].ID })
	for _, p := range sorted {
		cell := rosterIDCell(p)
		if isDormant(root, p, now) {
			cell = "💤 " + cell
		}
		b.WriteString(fmt.Sprintf("%s | %s | %s | ./%s\n", cell, orDash(p.Role), rosterStack(p), p.ID))
	}
	if len(heroes) > rosterLineCap {
		b.WriteString(fmt.Sprintf("\n<!-- %d 个人设超出 %d 行硬顶：折叠分组维度见 A4 -->\n", len(heroes), rosterLineCap))
	}
	b.WriteString(fmt.Sprintf("\n<!-- scanned %s -->\n", now.UTC().Format(time.RFC3339)))
	return b.String()
}

func rosterIDCell(p Hero) string {
	if p.Emoji != "" {
		return p.Emoji + " " + p.ID
	}
	return p.ID
}

// heroLastActive is the cheap last-active proxy for the dormant marker:
// max(journal.md mtime, hero.json.createdAt). Appearance history (block
// props.hero) joins here once A1.5 lands.
func heroLastActive(root string, p Hero) time.Time {
	var last time.Time
	if t, err := time.Parse(time.RFC3339, p.CreatedAt); err == nil {
		last = t
	}
	journal := filepath.Join(root, p.ID, ".hero", "MEMORY", "journal.md")
	if info, err := os.Stat(journal); err == nil && info.ModTime().After(last) {
		last = info.ModTime()
	}
	return last
}

func isDormant(root string, p Hero, now time.Time) bool {
	last := heroLastActive(root, p)
	if last.IsZero() {
		return false
	}
	return now.Sub(last) > dormantAfter
}

func rosterStack(p Hero) string {
	if p.Provider == "" && p.Model == "" {
		return "—"
	}
	if p.Provider == "" {
		return p.Model
	}
	if p.Model == "" {
		return p.Provider
	}
	return p.Provider + "/" + p.Model
}

func orDash(s string) string {
	if strings.TrimSpace(s) == "" {
		return "—"
	}
	return strings.TrimSpace(s)
}
